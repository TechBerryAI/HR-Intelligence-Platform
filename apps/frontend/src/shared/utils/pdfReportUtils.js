// ─── 4. Applications Report ───────────────────────────────────────────────────
export function generateApplicationsPdf(applications) {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })
  let y = drawPageHeader(doc, 'Applications Report', 'All job applications with ATS match scores and status')

  const shortlisted = applications.filter((a) => a.shortlisted).length
  const pending     = applications.filter((a) => a.status === 'pending').length
  const rejected    = applications.filter((a) => a.status === 'rejected').length
  const scores      = applications.map((a) => a.match_score).filter((v) => v != null)
  const avgScore    = scores.length
    ? (scores.reduce((s, v) => s + v, 0) / scores.length).toFixed(1)
    : '—'

  y = drawSummaryBox(doc, y, [
    { label: 'Total Applications', value: applications.length },
    { label: 'Shortlisted',        value: shortlisted, color: C.green },
    { label: 'Pending',            value: pending,     color: C.grey },
    { label: 'Rejected',           value: rejected,    color: rejected ? C.red : C.grey },
    { label: 'Avg Match Score',    value: avgScore + '%', color: C.accent },
  ])

  // Group by job
  const byJob = {}
  applications.forEach((a) => {
    const key = a.job_id || 'unknown'
    if (!byJob[key]) {
      byJob[key] = { title: a.job_title, company: a.job_company, hr: a.hr_name, rows: [] }
    }
    byJob[key].rows.push(a)
  })

  const H = doc.internal.pageSize.getHeight()
  // Min space needed for a job section (heading + 2 subtitle lines + table start) so we don't overlap footer
  const sectionHeadHeight = 22

  let firstSection = true
  for (const [jobId, group] of Object.entries(byJob)) {
    let startY = firstSection ? y : (doc.lastAutoTable.finalY + 10)
    firstSection = false

    // If we're too close to the footer, start on a new page to avoid overlap
    if (startY > H - FOOTER_ZONE_MM - sectionHeadHeight) {
      doc.addPage('a4', 'landscape')
      startY = 18
    }

    const hy = sectionHeading(doc, startY, 'Job: ' + (group.title || jobId) + '  (' + jobId + ')')

    doc.setFontSize(8)
    doc.setFont('helvetica', 'normal')
    setColor(doc, C.muted)
    doc.text(
      'Company: ' + (group.company || '—') +
      '   |   HR Admin: ' + (group.hr || '—') +
      '   |   Total Applications: ' + group.rows.length,
      16, hy + 4,
    )
    const jobShortlisted = group.rows.filter((r) => r.shortlisted).length
    const jobScores      = group.rows.map((r) => r.match_score).filter((v) => v != null)
    const jobAvg         = jobScores.length
      ? (jobScores.reduce((s, v) => s + v, 0) / jobScores.length).toFixed(1)
      : '—'
    doc.text('Shortlisted: ' + jobShortlisted + '   |   Avg Match Score: ' + jobAvg + '%', 16, hy + 9)

    autoTable(doc, {
      ...tableStyles(hy + 12),
      head: [['#', 'Candidate ID', 'Candidate Name', 'Email', 'Match %', 'Shortlist', 'Status', 'Applied On']],
      body: group.rows.map((a, idx) => [
        idx + 1,
        safe(a.candidate_id),
        safe(a.candidate_name),
        safe(a.candidate_email),
        a.match_score != null ? Math.round(a.match_score) + '%' : '—',
        a.shortlisted ? 'Yes' : 'No',
        safe(a.status) || 'applied',
        fmtDate(a.applied_at),
      ]),
      columnStyles: {
        0: { cellWidth: 10, halign: 'center' },
        1: { cellWidth: 22, fontStyle: 'bold', textColor: C.accent },
        2: { cellWidth: 38 },
        3: { cellWidth: 50 },
        4: { cellWidth: 18, halign: 'center', fontStyle: 'bold' },
        5: { cellWidth: 18, halign: 'center' },
        6: { cellWidth: 22, halign: 'center' },
        7: { cellWidth: 28 },
      },
      didDrawCell(data) {
        if (data.section === 'body') {
          if (data.column.index === 5) {
            if (data.cell.raw === 'Yes') {
              setColor(doc, C.green)
            } else {
              setColor(doc, C.grey)
            }
          }
          if (data.column.index === 6) {
            const v = data.cell.raw
            if (v === 'shortlisted') {
              setColor(doc, C.green)
            } else if (v === 'rejected') {
              setColor(doc, C.red)
            } else {
              setColor(doc, C.grey)
            }
          }
        }
      },
    })
  }

  drawPageFooter(doc)
  doc.save('applications-report-' + todayStr() + '.pdf')
}

