// ─── Helpers ──────────────────────────────────────────────────────────────────
export function todayStr() {
  return new Date().toISOString().split('T')[0]
}
function nowFull() {
  return new Date().toLocaleString('en-US', {
    weekday: 'long', year: 'numeric', month: 'long',
    day: 'numeric', hour: '2-digit', minute: '2-digit',
  }) + ' UTC'
}
function fmtDate(ts) {
  if (!ts) return '—'
  return new Date(ts).toLocaleDateString('en-US', {
    year: 'numeric', month: 'short', day: 'numeric',
  })
}
function safe(v) {
  return (v != null && v !== '') ? String(v) : '—'
}
function setColor(doc, arr) {
  doc.setTextColor(arr[0], arr[1], arr[2])
}

// ─── Shared page decorations ─────────────────────────────────────────────────
function drawPageHeader(doc, title, subtitle) {
  const W = doc.internal.pageSize.getWidth()

  // Top accent bar
  doc.setFillColor(C.accent[0], C.accent[1], C.accent[2])
  doc.rect(0, 0, W, 18, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(255, 255, 255)
  doc.text('HR JOB PORTAL', 14, 12)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.text('Head of HR Report', W - 14, 12, { align: 'right' })

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(20)
  setColor(doc, C.primary)
  doc.text(title, W / 2, 34, { align: 'center' })

  if (subtitle) {
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    setColor(doc, C.muted)
    doc.text(subtitle, W / 2, 41, { align: 'center' })
  }

  doc.setFontSize(8)
  setColor(doc, C.muted)
  doc.text('Generated on ' + nowFull(), 14, 48)

  doc.setDrawColor(C.border[0], C.border[1], C.border[2])
  doc.setLineWidth(0.5)
  doc.line(14, 51, W - 14, 51)

  return 56
}

// Content must stay above this Y so it doesn't overlap the footer
const FOOTER_ZONE_MM = 20

function drawPageFooter(doc) {
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setDrawColor(C.border[0], C.border[1], C.border[2])
    doc.setLineWidth(0.3)
    doc.line(14, H - 12, W - 14, H - 12)
    doc.setFontSize(7)
    setColor(doc, C.muted)
    doc.text('HR Intelligence — Confidential | Generated by Head of HR', 14, H - 7)
    doc.text('Page ' + i + ' of ' + pages, W - 14, H - 7, { align: 'right' })
  }
}

function drawSummaryBox(doc, y, items) {
  const W    = doc.internal.pageSize.getWidth()
  const colW = (W - 28) / items.length
  const boxH = 18

  doc.setFillColor(C.summaryBg[0], C.summaryBg[1], C.summaryBg[2])
  doc.setDrawColor(C.border[0], C.border[1], C.border[2])
  doc.setLineWidth(0.4)
  doc.roundedRect(14, y, W - 28, boxH, 2, 2, 'FD')

  items.forEach((item, i) => {
    const x  = 14 + i * colW
    if (i > 0) {
      doc.setDrawColor(C.border[0], C.border[1], C.border[2])
      doc.line(x, y + 2, x, y + boxH - 2)
    }
    const cx   = x + colW / 2
    const col  = item.color || C.accent
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(13)
    setColor(doc, col)
    doc.text(String(item.value), cx, y + 10, { align: 'center' })
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7.5)
    setColor(doc, C.muted)
    doc.text(item.label, cx, y + 15.5, { align: 'center' })
  })

  return y + boxH + 6
}

function sectionHeading(doc, y, text) {
  const W = doc.internal.pageSize.getWidth()
  doc.setFillColor(C.accentLt[0], C.accentLt[1], C.accentLt[2])
  doc.rect(14, y, W - 28, 8, 'F')
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  setColor(doc, C.primary)
  doc.text(text, 16, y + 5.5)
  return y + 10
}

function tableStyles(startY) {
  return {
    startY,
    margin: { left: 14, right: 14, bottom: FOOTER_ZONE_MM },
    styles: {
      fontSize: 8.5,
      cellPadding: { top: 3, bottom: 3, left: 4, right: 4 },
      lineColor: C.border,
      lineWidth: 0.3,
      textColor: C.text,
      font: 'helvetica',
    },
    headStyles: {
      fillColor: C.headerBg,
      textColor: C.headerTxt,
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    alternateRowStyles: { fillColor: C.rowAlt },
    bodyStyles:         { fillColor: C.rowEven },
    tableLineColor:     C.border,
    tableLineWidth:     0.3,
  }
}

// ─── 1. Admins Report ─────────────────────────────────────────────────────────
export function generateAdminsPdf(admins) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = drawPageHeader(doc, 'HR Admins Report', 'All registered HR administrators in the HR Intelligence system')

  const companies = [...new Set(admins.map((a) => a.company).filter(Boolean))]
  y = drawSummaryBox(doc, y, [
    { label: 'Total HR Admins',  value: admins.length },
    { label: 'Unique Companies', value: companies.length },
    { label: 'Report Date',      value: todayStr(), color: C.muted },
  ])

  y = sectionHeading(doc, y, 'Admin Account Details')
  autoTable(doc, {
    ...tableStyles(y),
    head: [['HR ID', 'Full Name', 'Email Address', 'Company', 'Date Joined']],
    body: admins.map((a) => [
      safe(a.hrid), safe(a.full_name), safe(a.email), safe(a.company), fmtDate(a.created_at),
    ]),
    columnStyles: {
      0: { cellWidth: 18, fontStyle: 'bold', textColor: C.accent },
      1: { cellWidth: 38 },
      2: { cellWidth: 55 },
      3: { cellWidth: 38 },
      4: { cellWidth: 32 },
    },
  })

  if (companies.length) {
    const afterY = doc.lastAutoTable.finalY + 8
    const hy = sectionHeading(doc, afterY, 'Companies Summary')
    autoTable(doc, {
      ...tableStyles(hy),
      head: [['Company', 'Admin Count']],
      body: companies.map((co) => [co, admins.filter((a) => a.company === co).length]),
      columnStyles: {
        0: { cellWidth: 80 },
        1: { cellWidth: 30, halign: 'center', fontStyle: 'bold', textColor: C.accent },
      },
    })
  }

  drawPageFooter(doc)
  doc.save('admins-report-' + todayStr() + '.pdf')
}

