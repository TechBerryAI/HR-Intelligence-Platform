#!/usr/bin/env python3
"""
Field-by-field accuracy + latency report for Document Intelligence Engine.

Parses gold lake source.txt → Form DTO / Canonical and compares to expected_*.
Writes docs/document_intelligence/ACCURACY_REPORT.md and LATENCY_REPORT.md
"""
from __future__ import annotations

import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / 'apps' / 'backend'
sys.path.insert(0, str(BACKEND))

from app.ai.document_intelligence.pipeline import (  # noqa: E402
    parse_jd_text_to_canonical,
    parse_resume_text_to_canonical,
)
from app.ai.parser.engine.hardware import detect_hardware_profile  # noqa: E402

LAKE = ROOT / 'ai' / 'dataset' / 'lake' / 'benchmark' / 'parsing' / 'v1'
DOCS = ROOT / 'docs' / 'document_intelligence'


def _norm(v):
    if isinstance(v, list):
        return [str(x).strip() for x in v]
    if v is None:
        return ''
    return str(v).strip()


def _compare_form(expected: dict, actual: dict) -> list[tuple[str, bool, object, object]]:
    rows = []
    for key, exp in expected.items():
        if key.startswith('_') or key == 'trace':
            continue
        act = actual.get(key, '')
        if isinstance(exp, list):
            ok = _norm(act) == _norm(exp)
        else:
            ok = _norm(act) == _norm(exp)
        rows.append((key, ok, exp, act))
    return rows


def run_suite(kind: str, limit: int | None = None):
    base = LAKE / ('resumes' if kind == 'resume' else 'jds')
    cases = sorted(p for p in base.iterdir() if p.is_dir() and (p / 'source.txt').exists())
    if limit:
        cases = cases[:limit]
    field_pass = field_total = 0
    case_pass = 0
    latencies = []
    failures = []
    parse_fn = parse_resume_text_to_canonical if kind == 'resume' else parse_jd_text_to_canonical

    for case in cases:
        text = (case / 'source.txt').read_text(encoding='utf-8')
        exp_form = json.loads((case / 'expected_form.json').read_text(encoding='utf-8'))
        t0 = time.perf_counter()
        profile, form, _toon = parse_fn(text)
        elapsed = time.perf_counter() - t0
        latencies.append(elapsed)
        actual = form.to_autofill_dict()
        rows = _compare_form(exp_form, actual)
        case_ok = True
        for key, ok, exp, act in rows:
            field_total += 1
            if ok:
                field_pass += 1
            else:
                case_ok = False
                failures.append(f'{case.name}.{key}: expected={exp!r} actual={act!r}')
        if case_ok:
            case_pass += 1
        # Optional canonical compare if present
        canon_path = case / 'expected_canonical.json'
        if canon_path.exists():
            expected_c = json.loads(canon_path.read_text(encoding='utf-8'))
            # Spot-check identity fields
            if kind == 'resume':
                checks = [
                    ('personal.full_name', profile.personal.full_name, (expected_c.get('personal') or {}).get('full_name')),
                    ('contact.email', profile.contact.email, (expected_c.get('contact') or {}).get('email')),
                ]
                for path, act, exp in checks:
                    if exp is None or exp == '':
                        continue
                    field_total += 1
                    if _norm(act) == _norm(exp):
                        field_pass += 1
                    else:
                        case_ok = False
                        failures.append(f'{case.name}.{path}: expected={exp!r} actual={act!r}')

    return {
        'kind': kind,
        'cases': len(cases),
        'cases_passed': case_pass,
        'field_pass': field_pass,
        'field_total': field_total,
        'accuracy': field_pass / field_total if field_total else 0.0,
        'latencies': latencies,
        'failures': failures,
    }


def main() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    hw = detect_hardware_profile()
    resume = run_suite('resume')
    jd = run_suite('jd')

    def _lat_block(name, lat):
        if not lat:
            return f'{name}: n/a\n'
        return (
            f'| {name} | {len(lat)} | {statistics.mean(lat)*1000:.1f} | '
            f'{statistics.median(lat)*1000:.1f} | '
            f'{sorted(lat)[int(0.95*(len(lat)-1))]*1000:.1f} |\n'
        )

    accuracy_md = f"""# Document Intelligence — Field Accuracy Report

**Date:** generated by `ai/eval/run_field_accuracy_report.py`  
**Hardware profile:** `{hw.name}` (vram_mb={hw.vram_mb}, cpus={hw.cpu_count})  
**Gold lake:** `ai/dataset/lake/benchmark/parsing/v1`

## Summary

| Suite | Cases | Cases 100% | Field PASS | Field Total | Accuracy | Target | Met |
|-------|-------|------------|------------|-------------|----------|--------|-----|
| Resume form | {resume['cases']} | {resume['cases_passed']} | {resume['field_pass']} | {resume['field_total']} | {resume['accuracy']*100:.2f}% | ≥99% | {'YES' if resume['accuracy'] >= 0.99 else 'NO'} |
| JD form | {jd['cases']} | {jd['cases_passed']} | {jd['field_pass']} | {jd['field_total']} | {jd['accuracy']*100:.2f}% | ≥99% | {'YES' if jd['accuracy'] >= 0.99 else 'NO'} |
| Frontend autofill (form keys) | — | — | — | — | {'100%' if resume['accuracy'] >= 1.0 and jd['accuracy'] >= 1.0 else 'see above'} | 100% | {'YES' if resume['accuracy'] >= 1.0 and jd['accuracy'] >= 1.0 else 'PARTIAL'} |

## Failures

"""
    fails = resume['failures'] + jd['failures']
    if not fails:
        accuracy_md += '_None — all compared fields PASS._\n'
    else:
        accuracy_md += '\n'.join(f'- `{f}`' for f in fails[:200]) + '\n'

    latency_md = f"""# Document Intelligence — Latency Report

**Hardware profile:** `{hw.name}`  
**Model hint:** `{hw.preferred_model_hint}`

| Suite | N | mean ms | p50 ms | p95 ms |
|-------|---|---------|--------|--------|
{_lat_block('Resume', resume['latencies'])}{_lat_block('JD', jd['latencies'])}
Notes: In-memory text path (source.txt), deterministic section parsers, LLM skipped when coverage gate passes.
"""

    (DOCS / 'ACCURACY_REPORT.md').write_text(accuracy_md, encoding='utf-8')
    (DOCS / 'LATENCY_REPORT.md').write_text(latency_md, encoding='utf-8')
    print(accuracy_md)
    print(f'Resume accuracy={resume["accuracy"]:.4f} JD accuracy={jd["accuracy"]:.4f}')
    print(f'Wrote {DOCS / "ACCURACY_REPORT.md"} and LATENCY_REPORT.md')


if __name__ == '__main__':
    main()
